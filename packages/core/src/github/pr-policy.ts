import { validateBranchName } from './branch-policy.js';
import type { VerificationEvidence } from './verification-evidence.js';

export interface PullRequestPolicyInput {
  repositoryId: string;
  expectedRepositoryId: string;
  baseBranch: string;
  defaultBranch: string;
  headBranch: string;
  changeId: string;
  baselineSha: string;
  expectedBaselineSha: string;
  evidence: VerificationEvidence;
  draft?: boolean;
}

export function renderReviewOnlyPRBody(input: {
  provider: string;
  changeId: string;
  affectedFiles: string[];
  baselineSha: string;
  evidence: VerificationEvidence;
  idempotencyKey: string;
}): string {
  const filesList = input.affectedFiles.map((f) => `- \`${f}\``).join('\n');
  return `## APIProof Automated Migration Proposal

> [!IMPORTANT]
> **HUMAN REVIEW MANDATORY — NO AUTOMATIC MERGE**
> This pull request was generated automatically by APIProof in response to a breaking change in vendor contract.

### Migration Summary
* **Provider:** ${input.provider}
* **Breaking Change ID:** \`${input.changeId}\`
* **Baseline Commit SHA:** \`${input.baselineSha}\`
* **Idempotency Key:** \`${input.idempotencyKey}\`

### Affected Files
${filesList}

### Verification Evidence
* **Proof Level:** \`${input.evidence.proofLevel}\`
* **Patch Applied:** ${input.evidence.patchApplied ? 'PASSED' : 'FAILED'}
* **Typecheck:** ${input.evidence.typecheckPassed ? 'PASSED' : 'FAILED'}
* **Tests:** ${input.evidence.testsPassed ? 'PASSED' : 'FAILED'}
* **Contract Verification:** ${input.evidence.contractPassed ? 'PASSED' : 'FAILED'}
* **Evidence Digest:** \`${input.evidence.evidenceDigest}\`
* **Verified At:** ${input.evidence.verifiedAt}

---
*Generated by APIProof (Review-Only Policy Enforced)*`;
}

export function validatePullRequestPolicy(input: PullRequestPolicyInput): { valid: boolean; status?: string; reason?: string } {
  if (!input.repositoryId || input.repositoryId !== input.expectedRepositoryId) {
    return { valid: false, status: 'GITHUB_REPOSITORY_NOT_APPROVED', reason: `Repository ID mismatch: ${input.repositoryId} !== ${input.expectedRepositoryId}` };
  }
  if (!input.baseBranch || input.baseBranch !== input.defaultBranch) {
    return { valid: false, status: 'GITHUB_OPERATION_REJECTED', reason: `Base branch '${input.baseBranch}' must match repository default branch '${input.defaultBranch}'.` };
  }
  const branchVal = validateBranchName(input.headBranch);
  if (!branchVal.valid) {
    return { valid: false, status: 'GITHUB_INVALID_BRANCH_NAME', reason: branchVal.reason ?? 'Invalid branch name.' };
  }
  if (!input.baselineSha || input.baselineSha !== input.expectedBaselineSha) {
    return { valid: false, status: 'GITHUB_BASE_CHANGED', reason: `Baseline SHA mismatch: ${input.baselineSha} !== ${input.expectedBaselineSha}` };
  }
  if (!input.evidence || !input.evidence.patchApplied || !input.evidence.typecheckPassed || !input.evidence.testsPassed || !input.evidence.contractPassed) {
    return { valid: false, status: 'GITHUB_EVIDENCE_MISMATCH', reason: 'PR policy rejected: Verification evidence incomplete or failing.' };
  }
  return { valid: true };
}
